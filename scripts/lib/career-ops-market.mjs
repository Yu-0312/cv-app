const MARKET_ALIASES = new Map([
  ["gb", "uk"],
  ["united kingdom", "uk"],
  ["usa", "us"],
  ["u.s.", "us"],
  ["united states", "us"],
  ["south korea", "kr"],
  ["korea", "kr"],
  ["uae", "ae"],
  ["czech republic", "cz"]
]);

export const MARKET_LOCATION_TERMS = Object.fromEntries(
  CAREER_OPS_MARKETS.map((market) => [market.code, market.locations])
);

const MARKET_BY_CODE = new Map(CAREER_OPS_MARKETS.map((market) => [market.code, market]));

function escapeRegExp(value) {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function includesLocationTerm(text, term) {
  const source = String(text || "");
  const needle = String(term || "").trim();
  if (!needle) return false;
  if (/^[a-z0-9 .'-]+$/i.test(needle)) {
    return new RegExp(`(^|[^a-z0-9])${escapeRegExp(needle).replace(/\s+/g, "\\s+")}([^a-z0-9]|$)`, "i").test(source);
  }
  return source.toLowerCase().includes(needle.toLowerCase());
}

export function marketCodes({ includeGlobal = false } = {}) {
  return CAREER_OPS_MARKETS
    .map((market) => market.code)
    .filter((code) => includeGlobal || code !== "global");
}

export function normalizeMarketCode(value) {
  const raw = String(value || "").trim().toLowerCase();
  if (!raw) return "";
  const alias = MARKET_ALIASES.get(raw) || raw;
  return MARKET_BY_CODE.has(alias) ? alias : "";
}

export function marketMeta(code) {
  return MARKET_BY_CODE.get(normalizeMarketCode(code)) || MARKET_BY_CODE.get("global");
}

export function inferMarketCodeFromText(...parts) {
  const text = parts.flat().map((part) => String(part || "").trim()).filter(Boolean).join("\n");
  if (!text) return "";
  const scores = new Map();
  for (const market of CAREER_OPS_MARKETS) {
    if (market.code === "global") continue;
    for (const term of market.locations) {
      if (!includesLocationTerm(text, term)) continue;
      const weight = term.length <= 3 ? 1 : term.length >= 10 ? 3 : 2;
      scores.set(market.code, (scores.get(market.code) || 0) + weight);
    }
  }
  return [...scores.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))[0]?.[0] || "";
}

export function isKnownMarketSearch(value) {
  const text = String(value || "").trim();
  if (!text) return false;
  return Boolean(normalizeMarketCode(text) || inferMarketCodeFromText(text));
}

export function inferJobMarketMetadata(job = {}, source = {}) {
  const configuredMarket = normalizeMarketCode(source.market || source.region || job.sourceConfiguredMarket || "");
  const existingMarket = normalizeMarketCode(job.sourceMarket || job.market || "");
  const configuredMeta = configuredMarket ? marketMeta(configuredMarket) : null;
  const configuredLocationHit = configuredMeta?.locations?.some((term) => includesLocationTerm(job.location, term));
  const locationMarket = configuredLocationHit ? configuredMarket : inferMarketCodeFromText(job.location);
  const inferredMarket = locationMarket || inferMarketCodeFromText(job.title, job.description, job.employmentType);
  const market = locationMarket || inferredMarket || existingMarket || configuredMarket || "global";
  const meta = marketMeta(market);
  return {
    sourceConfiguredMarket: configuredMarket || "",
    sourceMarket: market,
    market,
    country: meta.country || "",
    countryCode: meta.countryCode || "",
    region: meta.region || "",
    sourceCountry: meta.country || "",
    sourceCountryCode: meta.countryCode || ""
  };
}
